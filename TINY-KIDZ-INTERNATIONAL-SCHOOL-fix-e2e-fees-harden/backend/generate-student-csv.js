function generateStudentData() {
  const students = [];
  const headers =
    "StudentID,Name,Gender,ParentalSupport,ExtracurricularActivities\n";
  let csv = headers;

  for (let i = 1; i <= 1000; i++) {
    const firstName = firstNames[Math.floor(Math.random() * firstNames.length)];
    const lastName = lastNames[Math.floor(Math.random() * lastNames.length)];
    const name = `${firstName} ${lastName}`;
    const gender = genders[Math.floor(Math.random() * genders.length)];
    const parentalSupport =
      parentalSupports[Math.floor(Math.random() * parentalSupports.length)];
    const extracurricular =
      extracurriculars[Math.floor(Math.random() * extracurriculars.length)];

    csv += `${i},"${name}",${gender},${parentalSupport},${extracurricular}\n`;
  }

  const csvPath = path.join(
    __dirname,
    "demo-data",
    "student_performance_updated_1000.csv",
  );
  fs.writeFileSync(csvPath, csv);
  console.log(`✅ Generated 1000 student records in ${csvPath}`);
}

